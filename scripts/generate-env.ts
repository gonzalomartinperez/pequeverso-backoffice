// Regenerate docs/reference/env.md with `node scripts/generate-env.ts`.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ENVIRONMENT_VARIABLES } from "../src/server/environment-variables.ts";

export const ENV_DOC = "docs/reference/env.md";

export function renderEnv(): string {
  const sections = [
    ["Backoffice runtime", ENVIRONMENT_VARIABLES.runtime],
    ["Observability", ENVIRONMENT_VARIABLES.observability],
    ["Next.js standalone listener", ENVIRONMENT_VARIABLES.next],
  ] as const;
  const lines = [
    "# Environment variables",
    "",
    "Generated by `scripts/generate-env.ts` from the descriptions in `src/server/environment-variables.ts`.",
    "A dash indicates that no value is supplied by default.",
    "Production requires at least one complete OAuth provider pair.",
  ];
  for (const [heading, variables] of sections) {
    lines.push(
      "",
      `## ${heading}`,
      "",
      "| Variable | Requirement | Default | Purpose |",
      "| --- | --- | --- | --- |",
    );
    for (const [name, requirement, defaultValue, purpose] of variables) {
      lines.push(`| \`${name}\` | ${requirement} | ${defaultValue} | ${purpose} |`);
    }
  }
  return `${lines.join("\n")}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.resolve(import.meta.dirname, "..", ENV_DOC), renderEnv());
}
