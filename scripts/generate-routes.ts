// Regenerate docs/reference/routes.md with `node scripts/generate-routes.ts`.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { MATRIX } from "../tests/authz/matrix.ts";
import { type Files, readTree, surfaceOf } from "./authz-surface.ts";

export const ROUTES_DOC = "docs/reference/routes.md";
const ROOT = path.resolve(import.meta.dirname, "..");

function code(value: string): string {
  return `\`${value.replaceAll("|", "\\|")}\``;
}

export function renderRoutes(files: Files = readTree(ROOT)): string {
  const guards = new Map(MATRIX.map(({ id, guard }) => [id, guard]));
  const lines = [
    "# Routes and server actions",
    "",
    "Generated by `scripts/generate-routes.ts` from the app surface and `tests/authz/matrix.ts`.",
    "A dash means the entry has no matrix row. See the [permissions matrix](permissions.md) for caller outcomes.",
    "",
    "| Kind | URL path or action name | Source file | Guard |",
    "| --- | --- | --- | --- |",
  ];
  for (const { id, kind, file, name } of surfaceOf(files)) {
    if (kind === "proxy" || !file.startsWith("src/app/")) continue;
    const folders = file.split("/").slice(2, -1);
    const filename = path.basename(file);
    const dev = filename === "page.dev.tsx";
    if (kind === "page" && !dev && !/^page\.[cm]?[jt]sx?$/.test(filename)) continue;
    if (kind !== "action" && folders.some((folder) => folder.startsWith("_"))) continue;
    const url = `/${folders
      .filter((folder) => !/^\(.*\)$|^@/.test(folder))
      .map((folder) => folder.replace(/%5f/gi, "_"))
      .join("/")}`;
    const label = kind === "action" ? "Server action" : kind === "route" ? "Route handler" : "Page";
    const entry = kind === "action" ? name : kind === "route" ? `${name} ${url}` : url;
    const guard = guards.get(id);
    lines.push(
      `| ${label}${kind === "page" && dev ? " (development only)" : ""} | ${code(entry)} | ${code(file)} | ${guard ? code(guard) : "—"} |`,
    );
  }
  return `${lines.join("\n")}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.resolve(ROOT, ROUTES_DOC), renderRoutes());
}
