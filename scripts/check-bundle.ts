// Per-route first-load JavaScript, fonts and the Recharts client chunk, read from a Next 16 build.
//
//   node scripts/check-bundle.ts [--dist .next] [--public public] [--json out.json] [--enforce]
//
// Warn mode by default: budget overruns and regressions against quality/ratchets/bundle.json are
// printed (as GitHub annotations in CI) and the exit code stays 0. `--enforce` makes them fail.
//
// Spike result (Next 16.4.4, `next build --webpack`): there is no app-build-manifest.json and no
// diagnostics/route-bundle-stats.json. The per-route chunk list lives in
// `server/app/<route>/page_client-reference-manifest.js` (`clientModules[*].chunks`, a flat list of
// `id, path, id, path...`); the chunks every page loads are `rootMainFiles` in build-manifest.json.
// First-load JS of a route = rootMainFiles + the union of the JS paths in its client manifest.
// `polyfills-*.js` is `nomodule` and is excluded, as in Next's own accounting. The manifest of a
// route also carries the chunks of its parent layouts, and a chunk shared by several client
// modules is counted once; a route manifest can include chunks of sibling pages that share a
// module, so the figure is a conservative upper bound.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { runInNewContext } from "node:vm";
import { gzipSync } from "node:zlib";

export const ROUTE_BUDGET_GZ_BYTES = 170 * 1024;
export const FONT_BUDGET_BYTES = 160 * 1024;
/** A chunk is "the Recharts chunk" when it contains Recharts' class-name prefix. */
export const RECHARTS_MARKER = "recharts-";

export type ChunkSize = { path: string; rawBytes: number; gzBytes: number };
export type RouteSize = { route: string; chunks: number; rawBytes: number; gzBytes: number };
export type BundleReport = {
  routes: RouteSize[];
  fonts: { files: { path: string; bytes: number }[]; bytes: number };
  recharts: { chunks: ChunkSize[]; rawBytes: number; gzBytes: number; routes: string[] };
};
export type BundleRatchet = {
  budgets?: { routeFirstLoadGzBytes?: number; fontsBytes?: number };
  baseline?: { routes?: Record<string, number>; fontsBytes?: number; rechartsGzBytes?: number };
};

function size(file: string, cache: Map<string, ChunkSize>, rel: string): ChunkSize {
  const hit = cache.get(rel);
  if (hit) return hit;
  const buffer = readFileSync(file);
  const chunk = {
    path: rel,
    rawBytes: buffer.length,
    gzBytes: gzipSync(buffer, { level: 9 }).length,
  };
  cache.set(rel, chunk);
  return chunk;
}

function readClientManifestChunks(file: string): string[] {
  // The manifest is generated by the build and assigns a global; evaluate it in an empty context.
  const sandbox: { __RSC_MANIFEST?: Record<string, { clientModules?: Record<string, unknown> }> } =
    {};
  runInNewContext(readFileSync(file, "utf8"), sandbox);
  const entry = Object.values(sandbox.__RSC_MANIFEST ?? {})[0];
  const paths = new Set<string>();
  for (const module of Object.values(entry?.clientModules ?? {})) {
    const chunks = (module as { chunks?: unknown }).chunks;
    if (!Array.isArray(chunks)) continue;
    for (const chunk of chunks)
      if (typeof chunk === "string" && chunk.endsWith(".js")) paths.add(chunk);
  }
  return [...paths];
}

function routeName(appPath: string): string {
  return appPath.replace(/\/page$/, "").replace(/^$/, "/") || "/";
}

function listFonts(directories: string[]): { path: string; bytes: number }[] {
  const files: { path: string; bytes: number }[] = [];
  for (const directory of directories) {
    let names: string[] = [];
    try {
      names = readdirSync(directory);
    } catch {
      continue;
    }
    for (const name of names.sort())
      if (/\.(woff2?|ttf|otf)$/i.test(name))
        files.push({ path: join(directory, name), bytes: statSync(join(directory, name)).size });
  }
  return files;
}

export function measureBundle(dist: string, publicDir: string): BundleReport {
  const buildManifest = JSON.parse(readFileSync(join(dist, "build-manifest.json"), "utf8"));
  const appPaths: Record<string, string> = JSON.parse(
    readFileSync(join(dist, "server", "app-paths-manifest.json"), "utf8"),
  );
  const shared: string[] = (buildManifest.rootMainFiles ?? []).filter((f: string) =>
    f.endsWith(".js"),
  );
  const cache = new Map<string, ChunkSize>();
  const routes: RouteSize[] = [];
  const rechartsRoutes = new Set<string>();
  const rechartsChunks = new Map<string, ChunkSize>();
  const isRecharts = (rel: string) =>
    readFileSync(join(dist, rel), "utf8").includes(RECHARTS_MARKER);

  for (const appPath of Object.keys(appPaths).sort()) {
    if (!appPath.endsWith("/page")) continue;
    const manifest = join(
      dist,
      "server",
      "app",
      `${appPath.slice(1)}_client-reference-manifest.js`,
    );
    const files = [...new Set([...shared, ...readClientManifestChunks(manifest)])];
    const sizes = files.map((rel) => size(join(dist, rel), cache, rel));
    const route = routeName(appPath);
    routes.push({
      route,
      chunks: sizes.length,
      rawBytes: sizes.reduce((sum, c) => sum + c.rawBytes, 0),
      gzBytes: sizes.reduce((sum, c) => sum + c.gzBytes, 0),
    });
    for (const chunk of sizes)
      if (isRecharts(chunk.path)) {
        rechartsChunks.set(chunk.path, chunk);
        rechartsRoutes.add(route);
      }
  }
  const fonts = listFonts([join(dist, "static", "media"), join(publicDir, "fonts")]);
  const chunks = [...rechartsChunks.values()];
  return {
    routes,
    fonts: { files: fonts, bytes: fonts.reduce((sum, f) => sum + f.bytes, 0) },
    recharts: {
      chunks,
      rawBytes: chunks.reduce((sum, c) => sum + c.rawBytes, 0),
      gzBytes: chunks.reduce((sum, c) => sum + c.gzBytes, 0),
      routes: [...rechartsRoutes].sort(),
    },
  };
}

/** Every budget overrun and every regression against the ratchet baseline, as plain sentences. */
export function findViolations(report: BundleReport, ratchet: BundleRatchet = {}): string[] {
  const routeBudget = ratchet.budgets?.routeFirstLoadGzBytes ?? ROUTE_BUDGET_GZ_BYTES;
  const fontBudget = ratchet.budgets?.fontsBytes ?? FONT_BUDGET_BYTES;
  const out: string[] = [];
  for (const route of report.routes) {
    if (route.gzBytes > routeBudget)
      out.push(`${route.route}: first-load JS ${route.gzBytes} B gz exceeds budget ${routeBudget}`);
    const baseline = ratchet.baseline?.routes?.[route.route];
    if (baseline !== undefined && route.gzBytes > baseline)
      out.push(`${route.route}: first-load JS ${route.gzBytes} B gz regressed from ${baseline}`);
  }
  if (report.fonts.bytes > fontBudget)
    out.push(`fonts: ${report.fonts.bytes} B exceeds budget ${fontBudget}`);
  const fontBaseline = ratchet.baseline?.fontsBytes;
  if (fontBaseline !== undefined && report.fonts.bytes > fontBaseline)
    out.push(`fonts: ${report.fonts.bytes} B regressed from ${fontBaseline}`);
  const rechartsBaseline = ratchet.baseline?.rechartsGzBytes;
  if (rechartsBaseline !== undefined && report.recharts.gzBytes > rechartsBaseline)
    out.push(`recharts chunk: ${report.recharts.gzBytes} B gz regressed from ${rechartsBaseline}`);
  return out;
}

const kb = (bytes: number) => `${(bytes / 1024).toFixed(1)} KB`;

export function renderMarkdown(report: BundleReport, violations: string[]): string {
  const lines = [
    "### Bundle size (warn mode)",
    "",
    "| Route | Chunks | First-load JS gz | Raw |",
    "| --- | ---: | ---: | ---: |",
    ...report.routes.map(
      (r) => `| \`${r.route}\` | ${r.chunks} | ${kb(r.gzBytes)} | ${kb(r.rawBytes)} |`,
    ),
    "",
    `Fonts: ${kb(report.fonts.bytes)} (${report.fonts.files.length} files). Recharts chunk(s): ` +
      `${report.recharts.chunks.map((c) => c.path).join(", ") || "none"}, ` +
      `${kb(report.recharts.rawBytes)} raw, ${kb(report.recharts.gzBytes)} gz.`,
    "",
    violations.length ? violations.map((v) => `- ${v}`).join("\n") : "No budget overruns.",
  ];
  return lines.join("\n");
}

function main(argv: string[]): number {
  const flag = (name: string) => {
    const index = argv.indexOf(name);
    return index >= 0 ? argv[index + 1] : undefined;
  };
  const dist = flag("--dist") ?? ".next";
  const ratchetPath = flag("--ratchet") ?? "quality/ratchets/bundle.json";
  let ratchet: BundleRatchet = {};
  try {
    ratchet = JSON.parse(readFileSync(ratchetPath, "utf8"));
  } catch {
    console.warn(`No ratchet file at ${ratchetPath}; using the default budgets.`);
  }
  const report = measureBundle(dist, flag("--public") ?? "public");
  const violations = findViolations(report, ratchet);
  const markdown = renderMarkdown(report, violations);
  console.log(markdown);
  const jsonPath = flag("--json");
  if (jsonPath) writeFileSync(jsonPath, `${JSON.stringify(report, null, 2)}\n`);
  if (process.env.GITHUB_STEP_SUMMARY)
    writeFileSync(process.env.GITHUB_STEP_SUMMARY, `${markdown}\n`, { flag: "a" });
  const enforce = argv.includes("--enforce");
  for (const violation of violations)
    console.log(process.env.GITHUB_ACTIONS ? `::warning title=bundle::${violation}` : violation);
  return enforce && violations.length ? 1 : 0;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
